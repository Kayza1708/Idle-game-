/** Existing distributed contracts are captured without moving/changing source balance. */
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {MAX_ECONOMY_VALUE} from '../src/economy';
const source=readFileSync('src/economy.ts','utf8');
const divisor=Number(source.match(/export const hardwareMasteryLevel[^\n]*\/(\d+)\)\)/)![1]);
const cs=`// Generated by scripts/export-unity-lifetime.ts; source balance is unchanged.\nnamespace IdleIntelligence.Core { public static class LifetimeBalance {\npublic const string SourceHash=${JSON.stringify(createHash('sha256').update(source).digest('hex'))};\npublic const double Maximum=${MAX_ECONOMY_VALUE}d,MasteryDivisor=${divisor}d;\n} }\n`;
const path='IdleIntelligence/Assets/IdleIntelligence/Core/LifetimeBalance.g.cs';
if(process.argv.includes('--check')){if(readFileSync(path,'utf8')!==cs)throw Error('Stale lifetime constants');}else writeFileSync(path,cs);
console.log('Unity lifetime source contracts exported');
